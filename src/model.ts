const attachedPath = z.string().min(1).max(4096);
export const attachmentSchema = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('file'), path: attachedPath }),
  z.object({ kind: z.literal('folder'), path: attachedPath }),
  z.object({
    kind: z.literal('image'),
    file: z.string().regex(IMAGE_FILE),
    name: z.string().max(260),
  }),
  z.object({
    kind: z.literal('thread'),
    id: z.string().max(200),
    title: z.string().max(500).optional(),
  }),
  z.object({ kind: z.literal('diff') }),
  z.object({ kind: z.literal('terminal'), name: z.string().min(1).max(200) }),
]);
export type Attachment = z.infer<typeof attachmentSchema>;
export function attachmentLabel(attachment: Attachment): string {
  switch (attachment.kind) {
    case 'file':
    case 'folder':
      return attachment.path.split('/').pop() || attachment.path;
    case 'image':
      return attachment.name;
    case 'thread':
      return attachment.title ?? 'Thread';
    case 'diff':
      return 'Branch diff';
    case 'terminal':
      return attachment.name;
  }
}
