/** A finished plan is actionable only while its thread can accept the decision. */
export function canBuildPlan(session: Session): boolean {
  return Boolean(
    session.plan?.status === 'ready' &&
      session.plan.text.trim() &&
      !session.transition &&
      !session.inTerminal &&
      !session.observed &&
      ((session.status !== 'running' && session.status !== 'waiting') ||
        session.approval?.kind === 'plan'),
  );
}
