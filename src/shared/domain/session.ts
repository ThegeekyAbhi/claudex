export interface Session {
  id: string;
  provider: Provider;
  /** Which profile of the provider runs it. Unset on threads saved before profiles. */
  profileId?: string;
  title: string;
  /** `prompt` and `provider` titles may be replaced by the provider; `user` titles never are. */
  pinned?: boolean;
  titleSource?: 'prompt' | 'provider' | 'user';
  cwd: string;
  workspace: string;
  nativeId?: string;
  previousAgents?: { provider: Provider; profileId?: string; nativeId?: string }[];
  continuationContext?: string;
  parentId?: string;
  observed?: boolean;
  /** Running in the CLI's own terminal, so nothing here is running it. Not saved. */
  inTerminal?: boolean;
  /**
   * The last moment this thread matched the CLI's own transcript: a turn run here ended, or the
   * transcript was read. Anything the CLI recorded later came from somewhere else, like a terminal.
   */
  nativeSyncedAt?: number;
  /** First seen in the CLI's terminal, then opened here. */
  origin?: 'terminal';
  /** The thread this one continues, in another agent. Organisational only: no native link. */
  continuedFrom?: string;
  /** For each linked thread, the last of its messages this thread has been sent. */
  synced?: Record<string, string>;
  /** Started through a delegation; runs as its own provider session under its parent. */
  delegated?: boolean;
  /** The user's choice. Undefined keeps whatever the CLI is configured to use. */
  model?: string;
  effort?: string;
  thinking?: Thinking;
  /** What the provider actually reported using. */
  activeModel?: string;
  /** False when the catalog says the chosen model has no adaptive thinking. */
  adaptiveThinking?: boolean;
  /** Unset until you choose one, which leaves the CLI's own default in place. */
  mode?: AgentMode;
  /** The mode the CLI said it is in, for the turn that last reported one. */
  reportedMode?: string;
  /** What the CLI started this thread with, so leaving Ask or Plan can put it back. */
  nativeSettings?: NativeSettings;
  /** Reported by the CLI this session, for the inspector. Unset means it said nothing. */
  runtime?: RuntimeInfo;
  plan?: Plan;
  usage?: Usage;
  status: Status;
  messages: Message[];
  approval?: Approval;
  transition?: 'stopping' | 'resuming';
  createdAt: number;
  updatedAt: number;
}
