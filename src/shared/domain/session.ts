export type Catalog = Record<AgentKind, AgentCatalog>;
const NOT_LOADED: AgentCatalog = { status: 'loading', models: [] };
/** A profile's models. Profiles come and go, so a missing entry reads as still loading. */
export function catalogFor(catalog: Catalog, agent: AgentKind): AgentCatalog {
  return catalog[agent] ?? NOT_LOADED;
}
